"""Writes frontend/demo-data.js: stations, timetables and sample restaurants for the offline demo.

Run from backend/:  python scripts/build_demo_data.py
Keeps the browser-only demo in step with the mock providers without duplicating data by hand.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.providers import restaurants, trains  # noqa: E402

data = {
    "lines": {name: {**{k: v for k, v in spec.items() if k != "stations"},
                     "stations": [dict(zip(["code", "name", "city", "state", "lat", "lng", "mins"], st)) for st in spec["stations"]]}
              for name, spec in trains.LINES.items()},
    "consist": [dict(zip(["coach", "travel_class", "layout", "rows"], c)) for c in trains.CONSIST],
    "letters": trains.LETTERS,
    "restaurants": [restaurants._venue(v).model_dump(exclude={"matches", "slots", "tags", "distance_km"}) for v in restaurants.VENUES],
    "vocab": sorted(restaurants.VOCAB),
    "synonyms": restaurants.SYNONYMS,
}
out = Path(__file__).resolve().parents[2] / "frontend" / "demo-data.js"
out.write_text("/* Generated by backend/scripts/build_demo_data.py — sample data for the offline demo. */\nwindow.QUIK_DEMO = "
               + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
print(f"wrote {out} ({out.stat().st_size // 1024} KB)")
